export function generateSafeId(prefix: string): string {
  const randomPart =
    typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function'
      ? crypto.randomUUID().replace(/-/g, '').slice(0, 16)
      : `${Date.now()}_${Math.random().toString(36).slice(2, 10)}`;
  const id = `${prefix}_${randomPart}`.replace(/[^a-zA-Z0-9_-]/g, '_');
  return id.slice(0, BLUEPRINT_LIMITS.ID_MAX);
}

export function makeConversationId(listingId: string, buyerId: string): string {
  const raw = `${listingId}__${buyerId}`.replace(/[^a-zA-Z0-9_-]/g, '_');
  return raw.slice(0, BLUEPRINT_LIMITS.ID_MAX);
}

/**
 * Compresses an uploaded image file to a clean JPEG data URL guaranteed to stay
 * safely below the 350,000-character blueprint limit for Firestore documents.
 */
export async function compressImageToDataUrl(file: File): Promise<string> {
  if (!file.type.startsWith('image/')) {
    throw new Error('Veuillez sélectionner un fichier image valide (JPG, PNG, WebP).');
  }

  const dataUrl = await new Promise<string>((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => resolve(String(reader.result));
    reader.onerror = () => reject(new Error('Impossible de lire le fichier image.'));
    reader.readAsDataURL(file);
  });

  const img = await new Promise<HTMLImageElement>((resolve, reject) => {
    const image = new Image();
    image.onload = () => resolve(image);
    image.onerror = () => reject(new Error('Format image non pris en charge.'));
    image.src = dataUrl;
  });

  const maxDimension = 960;
  let { width, height } = img;
  if (width > maxDimension || height > maxDimension) {
    const ratio = Math.min(maxDimension / width, maxDimension / height);
    width = Math.round(width * ratio);
    height = Math.round(height * ratio);
  }

  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  if (!ctx) {
    throw new Error('Traitement image indisponible.');
  }
  ctx.drawImage(img, 0, 0, width, height);

  let quality = 0.82;
  let output = canvas.toDataURL('image/jpeg', quality);
  while (output.length > 300000 && quality > 0.35) {
    quality -= 0.12;
    output = canvas.toDataURL('image/jpeg', quality);
  }

  if (output.length > BLUEPRINT_LIMITS.IMAGE_URL_MAX) {
    throw new Error("L'image reste trop volumineuse après compression. Choisissez une photo plus légère.");
  }

  return output;
}
